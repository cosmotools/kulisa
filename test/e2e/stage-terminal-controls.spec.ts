import { taskPage, menuPage, inputPage } from './pages.ts';
// Stage terminal controls operate the visible terminal without sending search keys to its app.
import { test, expect } from './fixtures.ts';
import { focusWindow, showResources, notLoading, invoke } from './helpers.ts';
import { newTask, taskTab } from './tasks-helpers.ts';

test('terminal search survives task switches, navigates matches, and returns focus without typing into the app', async ({ core, ui, call }) => {
  await notLoading(ui);
  await call('terminal_run', { name: 'Search', command: 'node -e "console.log(\'marker-one marker-two\'); setInterval(()=>{},1000)"' });
  const read = async () => JSON.parse((await call('terminal_read', { name: 'Search' })).text).text;
  await expect.poll(read).toContain('marker-one marker-two');
  await focusWindow(core, ui);
  const pane = (await taskPage(ui)).locator('[data-stage-terminal]');
  const input = pane.locator('.xterm-helper-textarea');
  await input.focus();
  await input.press('Control+Shift+F');
  const query = pane.getByRole('textbox', { name: 'Find in terminal', exact: true });
  await expect(query).toBeFocused();
  await query.fill('marker');
  const first = await core((k) => k.shell.task.key), second = await newTask(core, ui);
  await taskTab(ui, first).click(); await notLoading(ui);
  await expect(query).toHaveValue('marker');
  await invoke(ui, 'task:close', second);
  const height = (await pane.locator('.xterm-screen').boundingBox()).height;
  await call('terminal_resize', { name: 'Search', size: { cols: 60, rows: 5 } });
  await expect.poll(async () => (await pane.locator('.xterm-screen').boundingBox()).height).toBeLessThan(height);
  const copySelection = async () => {
    await input.focus();
    await input.press('Control+Shift+C');
    await expect.poll(() => core((k) => k.electron.clipboard.readText())).toBe('marker');
  };
  await copySelection();
  await query.focus();
  await query.press('Enter');
  await copySelection();
  await query.focus();
  await query.press('Shift+Enter');
  await query.fill('no-such-output');
  await expect(pane.getByRole('status')).toHaveText('No matches');
  await query.press('Escape');
  await expect(query).toHaveCount(0);
  await expect(input).toBeFocused();
  expect(await read()).not.toContain('no-such-output');
  await call('terminal_close', { name: 'Search' });
});

test('Stage maximizes a terminal and follows agent activity without taking the agent keyboard focus', async ({ core, ui, call }) => {
  await notLoading(ui);
  await showResources(ui, 'Agents');
  const first = JSON.parse((await call('terminal_run', { name: 'First', command: 'node -e "setInterval(()=>{},1000)"' })).text);
  const second = JSON.parse((await call('terminal_run', { name: 'Second', command: 'node -e "setInterval(()=>{},1000)"' })).text);
  await call('stage_arrange', { layout: 'horizontal', overflow: true });
  const header = (await taskPage(ui)).locator(`[data-task-view][data-active] [data-panel="stage-terminal:${first.id}"]`);
  await header.getByRole('button', { name: 'Maximize pane', exact: true }).click();
  await expect((await taskPage(ui)).locator(`[data-stage-terminal="${second.id}"]`)).toBeHidden();
  await expect((await taskPage(ui)).locator(`[data-stage-terminal="${first.id}"]`)).toBeVisible();
  await expect((await taskPage(ui)).locator('[data-task-view][data-active]').getByTestId('terminal')).toBeVisible();
  await header.getByRole('button', { name: 'Restore pane', exact: true }).click();
  await expect((await taskPage(ui)).locator(`[data-stage-terminal="${second.id}"]`)).toBeVisible();
  await call('stage_arrange', { layout: 'tabs' });
  await (await taskPage(ui)).locator(`[data-task-view][data-active] [data-panel="stage-terminal:${second.id}"]`).getByText('Second', { exact: true }).click();
  await ui.getByRole('button', { name: 'Stage', exact: true }).click();
  await (await menuPage(ui)).getByRole('menuitemcheckbox', { name: 'Follow agent', exact: true }).click();
  await (await inputPage(ui)).keyboard.press('Escape');
  await focusWindow(core, ui);
  const agentInput = (await taskPage(ui)).locator('[data-task-view][data-active]').getByTestId('terminal').locator('.xterm-helper-textarea');
  await agentInput.focus();
  await call('terminal_read', { name: 'First' });
  await expect((await taskPage(ui)).locator(`[data-stage-terminal="${first.id}"]`)).toBeVisible();
  await expect(agentInput).toBeFocused();
  await (await taskPage(ui)).locator(`[data-task-view][data-active] [data-panel="stage-terminal:${second.id}"]`).getByText('Second', { exact: true }).click();
  await call('terminal_read', { name: 'First' });
  await expect(header).toHaveAttribute('data-agent-active', 'true');
  await expect((await taskPage(ui)).locator(`[data-stage-terminal="${second.id}"]`)).toBeVisible();
  await ui.getByRole('button', { name: 'Stage', exact: true }).click();
  await expect((await menuPage(ui)).getByRole('menuitemcheckbox', { name: 'Follow agent (paused)', exact: true })).not.toBeChecked();
  await (await menuPage(ui)).getByRole('menuitemcheckbox', { name: 'Follow agent (paused)', exact: true }).click();
  await (await menuPage(ui)).getByRole('menuitemcheckbox', { name: 'Follow agent', exact: true }).click();
  await (await inputPage(ui)).keyboard.press('Escape');
  await call('terminal_close', { name: 'First' });
  await call('terminal_close', { name: 'Second' });
});
